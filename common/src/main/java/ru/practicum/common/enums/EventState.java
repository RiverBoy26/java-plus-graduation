package ru.practicum.common.enums;

/**
 * Статусы жизненного цикла события.
 * Определяют текущее состояние события в системе.
 */
public enum EventState {

    /**
     * Событие ожидает модерации (не опубликовано).
     * Доступно для редактирования инициатором и администратором.
     */
    PENDING,

    /**
     * Событие опубликовано.
     * Доступно для просмотра пользователями.
     * Не может быть изменено инициатором.
     */
    PUBLISHED,

    /**
     * Событие отменено.
     * Недоступно для просмотра пользователями.
     * Может быть восстановлено только администратором.
     */
    CANCELED
}