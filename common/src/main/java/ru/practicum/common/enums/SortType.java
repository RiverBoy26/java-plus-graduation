package ru.practicum.common.enums;

/**
 * Типы сортировки для списка событий.
 */
public enum SortType {

    /**
     * Сортировка по дате и времени проведения события (по возрастанию).
     */
    EVENT_DATE,

    /**
     * Сортировка по количеству просмотров события (по убыванию).
     */
    VIEWS
}